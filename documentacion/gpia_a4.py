import time

def measure_latency(classifier, dataset_sample):

    start_time = time.time()

    for row in dataset_sample:
        classifier(
            row["text"],
            candidate_labels=[
                "World",
                "Sports",
                "Business",
                "Sci/Tech"
            ]
        )

    end_time = time.time()

    total_time = end_time - start_time
    avg_latency = total_time / len(dataset_sample)

    return total_time, avg_latency

